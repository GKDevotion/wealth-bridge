(function () {

  /* ── Scroll Reveal ── */
  var revealObs = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting) {
        e.target.classList.add('visible');
        revealObs.unobserve(e.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll('.reveal').forEach(function (el) { revealObs.observe(el); });

  /* ── Animated Counter ── */
  function animCounter(el) {
    var raw = parseFloat(el.dataset.counter);
    var suffix = el.dataset.suffix || '';
    var dur = 1800; var start = null;
    function step(ts) {
      if (!start) start = ts;
      var p = Math.min((ts - start) / dur, 1);
      var ease = 1 - Math.pow(1 - p, 3);
      var cur = Math.round(raw * ease);
      el.textContent = (cur >= 1000 ? cur.toLocaleString('en-IN') : cur) + suffix;
      if (p < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  }
  var cntObs = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (e.isIntersecting && !e.target.dataset.done) {
        e.target.dataset.done = '1';
        animCounter(e.target);
        cntObs.unobserve(e.target);
      }
    });
  }, { threshold: 0.5 });
  document.querySelectorAll('[data-counter]').forEach(function (el) { cntObs.observe(el); });
 
})();
</script>

