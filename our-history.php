<script>
(function () {

    /* Counter animation — for both hero strip and numbers section */
    function animateCounter(el) {
        var raw    = parseFloat(el.dataset.counter);
        var suffix = el.dataset.suffix || '';
        var dur    = 1800; var startTs = null;
        /* preserve any non-numeric prefix like ₹ */
        var text   = el.textContent;
        var prefix = '';
        if (text.charAt(0) === '₹') prefix = '₹';

        function step(ts) {
            if (!startTs) startTs = ts;
            var p = Math.min((ts - startTs) / dur, 1);
            var e = 1 - Math.pow(1 - p, 3);
            var v = raw < 10 ? (raw * e).toFixed(0) : Math.round(raw * e);
            var d = raw >= 1000 ? Number(v).toLocaleString('en-IN') : v;
            el.textContent = prefix + d + suffix;
            if (p < 1) requestAnimationFrame(step);
        }
        requestAnimationFrame(step);
    }

    var cEls = document.querySelectorAll('[data-counter]');
    if (cEls.length) {
        var obs = new IntersectionObserver(function (entries) {
            entries.forEach(function (e) {
                if (e.isIntersecting && !e.target.dataset.done) {
                    e.target.dataset.done = '1';
                    animateCounter(e.target);
                    obs.unobserve(e.target);
                }
            });
        }, { threshold: 0.4 });
        cEls.forEach(function (el) { obs.observe(el); });
    }

    /* Timeline era hover state propagation */
    document.querySelectorAll('.era').forEach(function (era) {
        era.addEventListener('mouseenter', function () { era.classList.add('hovered'); });
        era.addEventListener('mouseleave', function () { era.classList.remove('hovered'); });
    });

})();
</script>

