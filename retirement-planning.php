                        <div class="faq-q"><span>How much corpus do I need to retire comfortably?</span><i
                                class="fas fa-plus"></i></div>
                        <div class="faq-a">A common rule of thumb is 25× your annual expenses — known as the 25x Rule or
                            the 4% Rule. For example, if you spend ₹1.2 lakh/month (₹14.4L/year), you need approximately
                            ₹3.6 Crore. However, with India's higher inflation and longer lifespans, we typically
                            recommend 30–33× annual expenses. Our calculator and advisors give you a precise,
                            personalised number.</div>
                    </div>
                    <div class="faq-item">
                        <div class="faq-q"><span>At what age should I start retirement planning?</span><i
                                class="fas fa-plus"></i></div>
                        <div class="faq-a">The ideal answer is: yesterday. The second-best time is today. Even
                            ₹5,000/month invested at age 25 becomes ₹3.5 Crore by 60 at 12% CAGR. The same ₹5,000
                            started at 40 becomes only ₹50 lakhs. Starting early doesn't require big amounts — it
                            requires consistent habits. We'll help you start wherever you are.</div>
                    </div>
                    <div class="faq-item">
                        <div class="faq-q"><span>What is the best retirement plan in India?</span><i
                                class="fas fa-plus"></i></div>
                        <div class="faq-a">There is no single best plan — the right strategy is a combination: NPS for
                            tax efficiency and pension, EPF/VPF for guaranteed safe returns, equity mutual funds for
                            high growth, PPF for tax-free compounding, and SCSS/SWP for post-retirement income. The mix
                            depends on your age, risk profile, and income. That's exactly what we determine for you.
                        </div>
                    </div>
                    <div class="faq-item">
                        <div class="faq-q"><span>How does NPS help in retirement?</span><i class="fas fa-plus"></i>
                        </div>
                        <div class="faq-a">NPS offers market-linked returns (10–12% historically), an extra ₹50,000 tax
                            deduction (Sec 80CCD-1B) on top of the 80C limit, and a mandatory annuity component that
                            ensures lifelong pension income. At maturity (age 60), you can withdraw 60% tax-free and the
                            remaining 40% is used to purchase an annuity. It's a powerful tool for both accumulation and
                            pension income.</div>
                    </div>
                    <div class="faq-item">
                        <div class="faq-q"><span>What happens to my retirement plan if I retire early (before
                                60)?</span><i class="fas fa-plus"></i></div>
                        <div class="faq-a">Early retirement requires a larger corpus and a different withdrawal strategy
                            since you'll need income for 30–35+ years. We adjust NPS rules (partial withdrawal allowed
                            from age 60), shift to SWP-based income from equity funds, use SCSS only after age 60, and
                            supplement with annuities and rental income. Early retirement is achievable — it just needs
                            earlier planning and larger SIPs.</div>
                    </div>
                    <div class="faq-item">
                        <div class="faq-q"><span>How do you ensure I don't outlive my money?</span><i
                                class="fas fa-plus"></i></div>
                        <div class="faq-a">We use a "bucket strategy": Bucket 1 (0–5 years of expenses in liquid/debt
                            funds for immediate access), Bucket 2 (5–15 years in balanced funds), Bucket 3 (15+ years in
                            equity for growth). As Bucket 1 is depleted, Bucket 2 and 3 refill it. Additionally, we size
                            the SWP withdrawal rate below 4% annually, which statistically ensures the corpus lasts 30+
                            years even in poor market conditions.</div>
